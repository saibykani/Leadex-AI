"""Minimal state-machine orchestrator for agent turns.

Design (LangGraph-compatible by construction, so it can be swapped for `langgraph.graph.StateGraph` later):
  * State is a plain dict (`TurnState`), like a LangGraph TypedDict state.
  * A node is `fn(state) -> dict` returning a PARTIAL update that is merged into the state.
  * Edges are either fixed (`node -> next`) or conditional (`fn(state) -> next node name`).
  * `END` terminates. Mapping: Graph.add_node/add_edge/add_conditional_edges/set_entry_point mirror the
    LangGraph builder API one-to-one; `Graph.run(state)` corresponds to `compiled.invoke(state)`.

Turn graph:   retrieve -> generate -> [tools -> generate]* (max MAX_TOOL_ROUNDS) -> END
Every node appends a step log (`state["logs"]`) which the caller persists to `agent_logs`.
"""
import json
import time
from collections.abc import Callable
from typing import Any, TypedDict

from app.modules.agents import llm, rag, tools
from app.modules.agents.models import AIAgent

END = "__end__"
MAX_TOOL_ROUNDS = 2
MAX_STEPS = 12


class TurnState(TypedDict, total=False):
    agent: AIAgent
    env: tools.ToolEnv
    spec: llm.ModelSpec
    messages: list[dict]
    use_knowledge: bool
    requested_tools: list[dict]  # explicit invocations from the test lab: [{name, arguments}]
    pending_tools: list[dict]
    tool_calls: list[dict]
    tool_rounds: int
    citations: list[dict]
    retrieval_mode: str
    reply: str
    model: str
    simulated: bool
    error: str | None
    error_status: str | None
    logs: list[dict]
    extra_system: str  # appended to the system prompt (e.g. live-voice style rules)


class Graph:
    def __init__(self):
        self.nodes: dict[str, Callable[[dict], dict]] = {}
        self.edges: dict[str, str | Callable[[dict], str]] = {}
        self.entry: str | None = None

    def add_node(self, name: str, fn: Callable[[dict], dict]) -> None:
        self.nodes[name] = fn

    def add_edge(self, src: str, dst: str) -> None:
        self.edges[src] = dst

    def add_conditional_edges(self, src: str, router: Callable[[dict], str]) -> None:
        self.edges[src] = router

    def set_entry_point(self, name: str) -> None:
        self.entry = name

    def run(self, state: dict) -> dict:
        node, steps = self.entry, 0
        while node and node != END:
            steps += 1
            if steps > MAX_STEPS:
                state["error"] = "max_steps_exceeded"
                break
            t0 = time.perf_counter()
            update = self.nodes[node](state) or {}
            state.update(update)
            state.setdefault("logs", []).append({"step": node, "latency_ms": int((time.perf_counter() - t0) * 1000),
                                                 "data": update.get("_log")})
            state.pop("_log", None)
            edge = self.edges.get(node, END)
            node = edge(state) if callable(edge) else edge
        return state


def system_prompt(agent: AIAgent, citations: list[dict]) -> str:
    parts = [f"You are '{agent.name}', an AI assistant. Purpose: {agent.purpose or 'n/a'}.",
             f"Personality: {agent.personality or 'professional'}. Language: {agent.language}.",
             f"Always start a conversation with this disclosure: {agent.compliance_disclosure}",
             f"Business information: {agent.business_info or 'n/a'}",
             f"Qualification questions: {json.dumps(agent.qualification_questions or [])}",
             f"Objection handling: {json.dumps(agent.objection_handling or [])}",
             f"Escalation policy: {agent.escalation_policy or 'offer a human callback'}",
             "Never invent facts. If the knowledge below does not answer the question, say so."]
    if citations:
        parts.append("Knowledge (cite as [n]):\n" + "\n".join(f"[{i + 1}] {c['title']}: {c['text']}"
                                                              for i, c in enumerate(citations)))
    return "\n".join(parts)


def simulated_reply(agent: AIAgent, messages: list[dict], citations: list[dict], tool_calls: list[dict]) -> str:
    """Readable, clearly labelled template reply. Not generated by an AI model."""
    parts: list[str] = []
    if len([m for m in messages if m.get("role") == "user"]) <= 1:
        parts.append(agent.greeting or f"Hi, this is {agent.name}.")
        if agent.compliance_disclosure:
            parts.append(agent.compliance_disclosure)
    if citations:
        parts.append("Here is what I found: " + "; ".join(c["title"] for c in citations[:3]) + ".")
    qs = agent.qualification_questions or []
    parts.append(qs[0] if qs else "Could you tell me a little more about what you need?")
    note = "(Simulated template reply - switch the provider to Ollama for a real AI response.)"
    return " ".join(parts) + "\n\n" + note


# ------------------------------------------------------------------ nodes
def _retrieve(s: dict) -> dict:
    if not s.get("use_knowledge", True):
        return {"retrieval_mode": "disabled", "citations": []}
    env, query = s["env"], next((m["content"] for m in reversed(s["messages"]) if m.get("role") == "user"), "")
    mode, cits = rag.retrieve(env.db, env.ctx.organization_id, s["agent"].id, query)
    return {"retrieval_mode": mode, "citations": cits, "_log": {"mode": mode, "hits": len(cits)}}


def _generate(s: dict) -> dict:
    agent, spec = s["agent"], s["spec"]
    if spec.provider == "simulated":
        pending = list(s.get("requested_tools") or []) if not s.get("tool_rounds") else []
        if pending:
            return {"pending_tools": pending, "_log": {"provider": "simulated", "tool_requests": len(pending)}}
        text = simulated_reply(agent, s["messages"], s.get("citations", []), s.get("tool_calls", []))
        return {"reply": text, "simulated": True, "model": "template", "pending_tools": [],
                "_log": {"provider": "simulated"}}
    sys_text = system_prompt(agent, s.get("citations", []))
    if s.get("extra_system"):
        sys_text += "\n" + s["extra_system"]
    msgs = [{"role": "system", "content": sys_text}, *s["messages"]]
    for tc in s.get("tool_calls", []):
        msgs.append({"role": "tool", "content": json.dumps({k: tc.get(k) for k in ("name", "ok", "result", "error")},
                                                           default=str)})
    specs = [{"type": "function", "function": {"name": t.key, "description": t.description,
                                                "parameters": t.parameters}} for t in tools.allowed_specs(agent)]
    try:
        res = llm.chat(spec, msgs, specs if s.get("tool_rounds", 0) < MAX_TOOL_ROUNDS else None)
    except llm.LLMUnavailable as e:
        return {"error": e.message, "error_status": e.status, "reply": "", "pending_tools": [],
                "_log": {"provider": spec.provider, "error": e.status}}
    pending = list(s.get("requested_tools") or []) if not s.get("tool_rounds") else []
    pending += res.tool_calls
    return {"reply": res.text, "simulated": False, "model": res.model, "pending_tools": pending,
            "_log": {"provider": res.provider, "latency_ms": res.latency_ms, "tool_requests": len(res.tool_calls)}}


def _run_tools(s: dict) -> dict:
    done = list(s.get("tool_calls", []))
    for call in s.get("pending_tools", []):
        args: Any = call.get("arguments")
        if isinstance(args, str):
            try:
                args = json.loads(args)
            except ValueError:
                args = {}
        done.append(tools.invoke(s["env"], str(call.get("name")), args))
    return {"tool_calls": done, "pending_tools": [], "tool_rounds": s.get("tool_rounds", 0) + 1,
            "_log": {"executed": [d["name"] for d in done]}}


def _after_generate(s: dict) -> str:
    if s.get("error"):
        return END
    if s.get("pending_tools") and s.get("tool_rounds", 0) < MAX_TOOL_ROUNDS:
        return "tools"
    return END


def build_turn_graph() -> Graph:
    g = Graph()
    g.add_node("retrieve", _retrieve)
    g.add_node("generate", _generate)
    g.add_node("tools", _run_tools)
    g.set_entry_point("retrieve")
    g.add_edge("retrieve", "generate")
    g.add_conditional_edges("generate", _after_generate)
    g.add_edge("tools", "generate")
    return g
